class CADData:
    def __init__(self, df):
        self.df = df

    def get_entities(self, ColorCode, etype):

        # Force ColorCode column to int (safe conversion)
        df_fixed = self.df.copy()
        df_fixed["ColorCode"] = df_fixed["ColorCode"].astype(str).str.extract(r"(\d+)").astype(int)

        # If etype is LWPOLYLINE, allow both forms
        if etype == "LWPOLYLINE":
            valid_types = ["LWPOLYLINE", "POLYLINE"]
        else:
            valid_types = [etype]

        rows = df_fixed[
            (df_fixed["ColorCode"] == int(ColorCode)) &
            (df_fixed["Type"].isin(valid_types))
        ]

        return rows if not rows.empty else None




    def get_entity(self, ColorCode, etype):
        rows = self.get_entities(ColorCode, etype)
        return rows.iloc[0] if rows is not None else None



