def get_entity_color(entity, doc):
    if entity.dxf.hasattr("true_color"):
        return entity.rgb
    if entity.dxf.color not in (0, 256):
        return entity.dxf.color
    if entity.dxf.color == 256:
        layer = doc.layers.get(entity.dxf.layer)
        return layer.dxf.color
    return 7


def extract_entity_data(entity, doc):
    etype = entity.dxftype()
    data = {
        "Type": etype,
        "Layer": entity.dxf.layer if entity.dxf.hasattr("layer") else "",
        "ColorCode": get_entity_color(entity, doc),
        "StartX": "", "StartY": "", "StartZ": "",
        "EndX": "", "EndY": "", "EndZ": "",
        "Details": "",
    }

    try:
        if etype == "LINE":
            sx, sy, sz = entity.dxf.start
            ex, ey, ez = entity.dxf.end
            data.update({
                "StartX": sx, "StartY": sy, "StartZ": sz,
                "EndX": ex, "EndY": ey, "EndZ": ez,
                "Details": f"LINE from {entity.dxf.start} to {entity.dxf.end}",
            })

        elif etype == "CIRCLE":
            cx, cy, cz = entity.dxf.center
            data.update({
                "StartX": cx, "StartY": cy, "StartZ": cz,
                "Details": f"center={entity.dxf.center}, radius={entity.dxf.radius}",
            })

        elif etype == "ARC":
            cx, cy, cz = entity.dxf.center
            data.update({
                "StartX": cx, "StartY": cy, "StartZ": cz,
                "Details": (
                    f"center={entity.dxf.center}, radius={entity.dxf.radius}, "
                    f"start_angle={entity.dxf.start_angle}, end_angle={entity.dxf.end_angle}"
                ),
            })

        elif etype == "LWPOLYLINE":
            pts = [tuple(p[:2]) for p in entity.get_points()]
            if pts:
                data["StartX"], data["StartY"] = pts[0]
            data["Details"] = f"points={pts}"

        elif etype == "POLYLINE":
            pts = [tuple(v.dxf.location) for v in entity.vertices]
            if pts:
                data["StartX"], data["StartY"], data["StartZ"] = pts[0]
            data["Details"] = f"points={pts}"

        elif etype == "TEXT":
            ix, iy, iz = entity.dxf.insert
            data.update({
                "StartX": ix, "StartY": iy, "StartZ": iz,
                "Details": f"text={entity.dxf.text}",
            })

        elif etype == "MTEXT":
            ix, iy, iz = entity.dxf.insert
            data.update({
                "StartX": ix, "StartY": iy, "StartZ": iz,
                "Details": f"text={entity.text}",
            })

        elif etype == "INSERT":
            ix, iy, iz = entity.dxf.insert
            data.update({
                "StartX": ix, "StartY": iy, "StartZ": iz,
                "Details": f"block_name={entity.dxf.name}",
            })

        else:
            data["Details"] = "Unsupported entity type"

    except Exception:
        data["Details"] = "Error parsing entity"

    return data


def dxf_to_csv_in_memory(dxf_path):
    try:
        doc = ezdxf.readfile(dxf_path)
        msp = doc.modelspace()

        rows = [extract_entity_data(e, doc) for e in msp]

        output = io.StringIO()
        writer = csv.DictWriter(output,
            fieldnames=["Type","Layer","ColorCode","StartX","StartY","StartZ",
                        "EndX","EndY","EndZ","Details"])
        writer.writeheader()
        writer.writerows(rows)

        return output.getvalue()

    except Exception as e:
        print("❌ Error:", e)
        print(traceback.format_exc())
        return ""

