SCALE = 1.0  # 1 mm = 1 m  (adjust if needed)

# ----------------------------------------------------------
# Extract Polyline Points  (removes Z coordinate)
# ----------------------------------------------------------
def extract_points(details):
    if not isinstance(details, str):
        return []
    if "points=" not in details:
        return []

    try:
        match = re.search(r"points\s*=\s*(\[.*\])", details)
        if not match:
            return []

        cleaned = re.sub(r"np\.float64\((.*?)\)", r"\1", match.group(1))
        pts = ast.literal_eval(cleaned)

        # --- IMPORTANT FIX ---
        # Convert (x, y, z) → (x, y)
        pts2 = [(p[0], p[1]) for p in pts]

        return pts2

    except:
        return []


