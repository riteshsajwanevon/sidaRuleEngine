# Main Calculation Router
# ----------------------------------------------------------
def calculate(action, entityType, ColorCode,
              ColorCode2=None, type2=None, db=None):

    entity = db.get_entity(ColorCode, entityType)

    if entity is None:
        return 0

    if action == "area":
        return calc_area(entity)

    if action == "sum_area":
        entities = db.get_entities(ColorCode, entityType)
        if entities is None:
            return 0
        total = 0
        for _, ent in entities.iterrows():
            total += calc_area(ent)
        return total

    if action == "length":
        return calc_length(entity)

    if action == "parallel_distance":
        entity2 = db.get_entity(ColorCode2, type2)
        if entity2 is None:
            return 0
        return calc_parallel_distance(entity, entity2)

    return 0

