def location_matches(rule_location, input_location):
    if rule_location == input_location:
        return True
    if rule_location == "Urban/Rural":
        return input_location in ["Urban", "Rural"]
    return False

def area_type_matches(rule_area_type, input_area_type):
    # Split rule entry by "/" → e.g. "Cottage/Micro/Household"
    allowed_types = [t.strip().lower() for t in rule_area_type.split("/")]

    # Normalize input
    input_type = input_area_type.strip().lower()

    # Return True if input matches any allowed type
    return input_type in allowed_types

# ------------------------------------------
# SELECT RULE BASED ON INPUT CONDITIONS
# ------------------------------------------
def get_applicable_rule(area_type, location, plot_area, road_width):
    for rule in RULES:
        if not area_type_matches(rule["area_type"], area_type):
            continue
        if not location_matches(rule["location"], location):
            continue

        if not (rule["plot_min"] <= plot_area <= (rule["plot_max"] if rule["plot_max"] else plot_area)):
            continue

        if road_width < rule["road_min"]:
            continue

        if rule.get("road_max") is not None and road_width >= rule["road_max"]:
            continue

        return rule

    return None


